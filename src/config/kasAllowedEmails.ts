/**
 * Look up an employee in the official KAS whitelist by email, username, or ID (case-insensitive).
 */
export function findAllowedKasEmployee(identifier: string): KasAllowedEmployee | null {
  const clean = (identifier || '').trim().toLowerCase();
  if (!clean) return null;
  return (
    KAS_ALLOWED_EMPLOYEES.find(
      (emp) =>
        emp.email.toLowerCase() === clean ||
        emp.username.toLowerCase() === clean ||
        emp.id.toLowerCase() === clean
    ) || null
  );
}

/**
 * Checks if an email is explicitly excluded (e.g., buffet kitchen `o.saeed.hospitality@kas.sa`).
 */
export function getExcludedEmailReason(identifier: string): string | null {
  const clean = (identifier || '').trim().toLowerCase();
  const normalized = clean.includes('@') ? clean : `${clean}@kas.sa`;
  const match = EXCLUDED_KAS_EMAILS[normalized] || EXCLUDED_KAS_EMAILS[clean];
  return match ? match.reasonAr : null;
}
